"""
Calculator module with basic arithmetic functions.
"""

def add(a, b):
    """Return the sum of a and b."""
    return a + b

def multiply(a, b):
    """Return the product of a and b."""
    return a * b

def subtract(a, b):
    """Return the result of a minus b."""
    return a - b

def divide(a, b):
    """Return the result of a divided by b."""
    return a / b
